    private void comtableMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_comtableMouseClicked
        int index=comtable.getSelectedRow();
        TableModel model=comtable.getModel();
        String id=model.getValueAt(index,0).toString();
        jTextField1.setText(id);
         try {
        Connection con = ConnectionProvider.getCon();
        PreparedStatement pst = con.prepareStatement("SELECT image FROM ecomplaint WHERE ComplaintID = ?");
        pst.setString(1, id);
        ResultSet rs = pst.executeQuery();

        if (rs.next()) {
            byte[] imgData = rs.getBytes("image");

            if (imgData != null) {
                ImageIcon icon = new ImageIcon(imgData);
                Image img = icon.getImage().getScaledInstance(imageLabel.getWidth(), imageLabel.getHeight(), Image.SCALE_SMOOTH);
                imageLabel.setIcon(new ImageIcon(img));
            } else {
                imageLabel.setIcon(null); 
                JOptionPane.showMessageDialog(null, "No image available for this record.");
            }
        }
    } catch (SQLException e) {
        JOptionPane.showMessageDialog(null, "Error loading image: " + e.getMessage());
    }

    }//GEN-LAST:event_comtableMouseClicked

