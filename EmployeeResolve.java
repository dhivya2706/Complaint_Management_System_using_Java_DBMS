   public static Image getScaledImage(Image srcImg, int targetWidth, int targetHeight) {
    int imgWidth = srcImg.getWidth(null);
    int imgHeight = srcImg.getHeight(null);
    double scaleX = (double) targetWidth / imgWidth;
    double scaleY = (double) targetHeight / imgHeight;
    double scaleFactor = Math.min(scaleX, scaleY);
    int newWidth = (int) (imgWidth * scaleFactor);
    int newHeight = (int) (imgHeight * scaleFactor);
    BufferedImage bufferedImg = new BufferedImage(newWidth, newHeight, BufferedImage.TYPE_INT_ARGB);
    Graphics2D g2 = bufferedImg.createGraphics();
    g2.setRenderingHint(RenderingHints.KEY_INTERPOLATION, RenderingHints.VALUE_INTERPOLATION_BICUBIC);
    g2.setRenderingHint(RenderingHints.KEY_RENDERING, RenderingHints.VALUE_RENDER_QUALITY);
    g2.setRenderingHint(RenderingHints.KEY_ANTIALIASING, RenderingHints.VALUE_ANTIALIAS_ON);
    g2.drawImage(srcImg, 0, 0, newWidth, newHeight, null);
    g2.dispose();
    return bufferedImg;
}
