    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        String id=jTextField1.getText();
        String d =jTextArea1.getText();
        String s=(String)jComboBox1.getSelectedItem();
        Connection con = null;
        try {
        con = ConnectionProvider.getCon();
        Statement st = con.createStatement();
        if (s.equals("Solved")) {
           st.executeUpdate("INSERT INTO solved_ecomplaint (ComplaintID, CustID, Type, Description, Incident, ComDate, Level, image, Status, assign, solution) " +
                 "SELECT ComplaintID, CustID, Type, Description, Incident, ComDate, Level, image, 'Solved', assign, '" + d + "' " +
                 "FROM ecomplaint WHERE ComplaintID = '" + id + "'");

            st.executeUpdate("DELETE FROM ecomplaint WHERE ComplaintID = '" + id + "'");
            
            JOptionPane.showMessageDialog(null, "Complaint marked as solved and moved to solved_ecomplaint.");
        } else {
            st.executeUpdate("UPDATE ecomplaint SET solution='" + d + "', status='" + s + "' WHERE ComplaintID='" + id + "'");
            JOptionPane.showMessageDialog(null, "Complaint updated successfully.");
        }
       }
        catch(SQLException e)
        {
             if (con != null) try {
                 con.rollback();
             } catch (SQLException ex) {
                 Logger.getLogger(EmployeeResolve.class.getName()).log(Level.SEVERE, null, ex);
             }
            JOptionPane.showMessageDialog(null,"Error: " + e.getMessage());
            setVisible(false);
        }
    }//GEN-LAST:event_jButton1ActionPerformed

