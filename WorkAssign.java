    private void formComponentShown(java.awt.event.ComponentEvent evt) {//GEN-FIRST:event_formComponentShown
         try
        {
            Connection con=ConnectionProvider.getCon();
            Statement st=con.createStatement();
            ResultSet rs=st.executeQuery("select ecomplaint.ComplaintID,ecomplaint.custID,ecomplaint.Type,ecomplaint.Level from ecomplaint");
            comtable.setModel(DbUtils.resultSetToTableModel(rs));
            ResultSet rs1=st.executeQuery("select employee.employeeID,employee.employeeName,employee.ROLE,employee.ContactNo from employee");
            emptable.setModel(DbUtils.resultSetToTableModel(rs1));
        }
        catch(SQLException e)
        {
            JOptionPane.showMessageDialog(null,"Connection Error"+e.getMessage());
        }
    }//GEN-LAST:event_formComponentShown

