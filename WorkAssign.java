    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        String id=jTextField1.getText();
        String a=jTextField3.getText();
        String ph;
        String message="An job has been assigned to your account.\n Kindly resolve and verfiy it.By SHAL";
         try
        {
            Connection con = ConnectionProvider.getCon();
            Statement st=con.createStatement();
            st.executeUpdate("Update ecomplaint set assign='"+a+"' where complaintID='"+id+"'");
            JOptionPane.showMessageDialog(null,"Job Assigned Successfully");
            ResultSet rs=st.executeQuery("select contactno from employee where employeeid='"+a+"'");
            if(rs.next()) 
            {
                ph = "+91" + rs.getString(1);
                SmsSender.sms(ph, message);
            }
            else
            {
                JOptionPane.showMessageDialog(null, "Employee not found.");
            }
        }
        catch(SQLException e)
        {
            JOptionPane.showMessageDialog(null,"Error: " + e.getMessage());
            setVisible(false);
        }
    }//GEN-LAST:event_jButton1ActionPerformed

