    private void formComponentShown(java.awt.event.ComponentEvent evt) {//GEN-FIRST:event_formComponentShown
          try {
        Connection con = ConnectionProvider.getCon();
        if (con != null) {
            PreparedStatement pst = con.prepareStatement("SELECT * FROM adminlogin WHERE username=?");
            pst.setString(1, user);  
            ResultSet rs = pst.executeQuery();

            if (rs.next()) {
                jLabel1.setText(rs.getString(1));  
                jTextField2.setText(rs.getString(4));  
                jTextField3.setText(rs.getString(7));  
                jTextField4.setText(rs.getString(6));  
                jTextArea1.setText(rs.getString(8));  
            } else {
                System.out.println("No user found with username: " + user);
            }
        } else {
            System.out.println("Database connection failed");
        }
    } catch (SQLException e) {
        JOptionPane.showMessageDialog(null, "Error: " + e.getMessage());
    }
    }//GEN-LAST:event_formComponentShown

